// Uniform cubic B-spline basis; the curve approximates its control points.
glm::vec2 bsplinePoint(const glm::vec2 &p0, const glm::vec2 &p1,
                       const glm::vec2 &p2, const glm::vec2 &p3, float t) {
    float t2 = t * t;
    float t3 = t2 * t;
    float b0 = (-t3 + 3.0f * t2 - 3.0f * t + 1.0f) / 6.0f;
    float b1 = (3.0f * t3 - 6.0f * t2 + 4.0f) / 6.0f;
    float b2 = (-3.0f * t3 + 3.0f * t2 + 3.0f * t + 1.0f) / 6.0f;
    float b3 = t3 / 6.0f;
    return b0 * p0 + b1 * p1 + b2 * p2 + b3 * p3;
}

// Closed curves have n wrapping segments; open curves have n - 3 segments.
std::vector<glm::vec2> evalBSpline(const std::vector<glm::vec2> &pts, bool closed) {
    std::vector<glm::vec2> out;
    int n = (int)pts.size();
    if (n < 4) return out;

    int segCount = closed ? n : n - 3;
    for (int s = 0; s < segCount; s++) {
        const glm::vec2 &p0 = pts[s % n];
        const glm::vec2 &p1 = pts[(s + 1) % n];
        const glm::vec2 &p2 = pts[(s + 2) % n];
        const glm::vec2 &p3 = pts[(s + 3) % n];
        // Do not duplicate shared endpoints or the closed curve's first sample.
        int last = (s == segCount - 1 && !closed) ? kSamplesPerSeg : kSamplesPerSeg - 1;
        for (int i = 0; i <= last; i++) {
            float t = (float)i / (float)kSamplesPerSeg;
            out.push_back(bsplinePoint(p0, p1, p2, p3, t));
        }
    }
    return out;
}

void buildOffsets(const std::vector<glm::vec2> &center, bool closed,
                  std::vector<glm::vec2> &inner, std::vector<glm::vec2> &outer) {
    int n = (int)center.size();
    float half = kTrackWidth * 0.5f;
    for (int i = 0; i < n; i++) {
        glm::vec2 prev, next;
        if (closed) {
            prev = center[(i - 1 + n) % n];
            next = center[(i + 1) % n];
        } else {
            prev = center[i > 0 ? i - 1 : i];
            next = center[i < n - 1 ? i + 1 : i];
        }
        glm::vec2 tangent = next - prev;
        float len = glm::length(tangent);
        if (len > 1e-6f) tangent /= len;
        glm::vec2 normal(-tangent.y, tangent.x);
        outer.push_back(center[i] + normal * half);
        inner.push_back(center[i] - normal * half);
    }
}

glm::vec2 trackCentroid(const std::vector<glm::vec2> &center) {
    glm::vec2 centroid(0.0f);
    for (const auto &point : center) centroid += point;
    if (!center.empty()) centroid /= (float)center.size();
    return centroid;
}

glm::vec3 trackPointToWorld(const glm::vec2 &point, const glm::vec2 &centroid) {
    // Screen y grows downward, so flip it when mapping to world z.
    return glm::vec3((point.x - centroid.x) * kWorldScale, 0.0f,
                     -(point.y - centroid.y) * kWorldScale);
}

namespace {

glm::vec2 animationTangent(const std::vector<glm::vec2> &center, int i, bool closed) {
    int n = (int)center.size();
    int prev = closed ? (i - 1 + n) % n : (i > 0 ? i - 1 : i);
    int next = closed ? (i + 1) % n : (i < n - 1 ? i + 1 : i);
    glm::vec2 tangent = center[next] - center[prev];
    if (glm::dot(tangent, tangent) > 1e-12f) return tangent;

    // Repeated samples (or a cusp) can cancel the centered difference. Prefer
    // the next distinct sample, then the previous one at an open endpoint.
    for (int step = 1; step < n; ++step) {
        if (!closed && i + step >= n) break;
        tangent = center[(i + step) % n] - center[i];
        if (glm::dot(tangent, tangent) > 1e-12f) return tangent;
    }
    for (int step = 1; step < n; ++step) {
        if (!closed && i - step < 0) break;
        tangent = center[i] - center[(i - step + n) % n];
        if (glm::dot(tangent, tangent) > 1e-12f) return tangent;
    }
    return glm::vec2(0.0f);
}

} // namespace

bool writeTrackAnimation(std::ostream &out, const std::vector<glm::vec2> &center,
                         const glm::vec2 &centroid, bool closed) {
    if (center.size() < 2) return false;

    std::streamsize precision = out.precision();
    out << std::setprecision(std::numeric_limits<float>::max_digits10);
    out << "# Track centerline animation generated by trackgen\n";
    out << "# Tx Ty Tz Sx Sy Sz Rx Ry Rz (degrees; car forward is +Z)\n";
    float yaw = 0.0f;
    for (int i = 0; i < (int)center.size(); ++i) {
        glm::vec3 position = trackPointToWorld(center[i], centroid) * kTrackSceneScale;
        position.y = kTrackSceneHeight;
        glm::vec2 tangent = animationTangent(center, i, closed);
        if (glm::dot(tangent, tangent) > 1e-12f) {
            // A yaw around +Y rotates the car's local +Z toward (dx, 0, -dy).
            yaw = glm::degrees(std::atan2(tangent.x, -tangent.y));
        }
        out << position.x << " " << position.y << " " << position.z << " "
            << kCarScale << " " << kCarScale << " " << kCarScale << " 0 " << yaw << " 0\n";
    }
    out.precision(precision);
    return static_cast<bool>(out);
}

bool writeTrackAnimation(const std::string &path, const std::vector<glm::vec2> &center,
                         const glm::vec2 &centroid, bool closed) {
    if (center.size() < 2) {
        fprintf(stderr, "ERROR: not enough samples to build an animation (need >= 2)\n");
        return false;
    }
    std::ofstream out(path);
    if (!out) {
        fprintf(stderr, "ERROR: could not open %s for writing\n", path.c_str());
        return false;
    }
    bool written = writeTrackAnimation(out, center, centroid, closed);
    out.close();
    if (!written || !out) {
        fprintf(stderr, "ERROR: could not write animation %s\n", path.c_str());
        return false;
    }
    printf("Wrote %s (%zu animation frames)\n", path.c_str(), center.size());
    return true;
}
